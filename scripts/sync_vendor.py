def path_specs(source: dict) -> list:
    """Normalise and safety-check a source's declared paths."""
    specs = source.get("paths")
    if not specs:
        _fail(f"[{source.get('id')}] manifest source declares no `paths`")
    sid = source["id"]
    out = []
    for spec in specs:
        kind = spec.get("kind", SKILL_COLLECTION)
        if kind not in (SKILL_COLLECTION, SUPPORT):
            _fail(f"[{sid}] unknown path kind `{kind}`")
        out.append(
            {
                "from": safe_segment(spec.get("from", ""), "paths[].from", sid),
                "to": safe_segment(spec.get("to", ""), "paths[].to", sid),
                "kind": kind,
                "include": spec.get("include"),
                "file_include": spec.get("file_include"),
                "exclude": spec.get("exclude", []),
                "exclude_reasons": spec.get("exclude_reasons", {}),
            }
        )

    # Overlapping destinations let one mapping delete a tree owned by another.
    for i, a in enumerate(out):
        for j, b in enumerate(out):
            if i >= j:
                continue
            pa, pb = a["to"], b["to"]
            if pa == pb:
                _fail(f"[{sid}] two paths map to the same destination `{pa or '.'}`")
            if pa == "" or pb == "" or pb.startswith(pa + "/") or pa.startswith(pb + "/"):
                _fail(
                    f"[{sid}] destinations `{pa or '.'}` and `{pb or '.'}` overlap. Nested or "
                    f"root-level mappings alongside siblings let one mapping delete another's "
                    f"content. Give each mapping its own subdirectory."
                )
    return out


def process_source(source: dict, checkout: Path, sha: str, apply: bool) -> dict:
    sid = source["id"]
    dest_rel = safe_segment(source.get("dest", ""), "dest", sid)
    if not dest_rel:
        _fail(f"[{sid}] `dest` is required")
    dest_root = resolve_under(REPO_ROOT, dest_rel, "dest", sid)
    plan = path_specs(source)
    added, removed, changed = [], [], []
    owned = []

    for spec in plan:
        upstream = resolve_under(checkout, spec["from"], "paths[].from", sid)
        if not upstream.is_dir():
            _fail(f"[{sid}] upstream path not found: {spec['from'] or '<root>'}")
        assert_no_symlinks(upstream, sid, spec["from"] or ".")
        local = resolve_under(dest_root, spec["to"], "paths[].to", sid)
        label = spec["to"] or "."

        if spec["kind"] == SKILL_COLLECTION:
            selected = _selected(_child_dirs(upstream), spec["include"], spec["exclude"])
            spec["selected"] = selected
            spec["with_skill"] = [n for n in selected if _has_skill(upstream / n)]
            owned += [posixpath.join(spec["to"], n) if spec["to"] else n for n in selected]
            existing = _child_dirs(local)
            added += [f"{label}/{n}" for n in selected if n not in existing]
            changed += [
                f"{label}/{n}"
                for n in selected
                if n in existing and tree_digest(local / n) != tree_digest(upstream / n)
            ]
            if apply:
                for name in selected:
                    target = local / name
                    if target.exists():
                        shutil.rmtree(target)
                    _copy_tree(upstream / name, target)
                    upstream_path = posixpath.join(spec["from"], name) if spec["from"] else name
                    kind_label = "skill" if _has_skill(target) else "shared support directory"
                    _write(
                        target / "PROVENANCE.md",
                        provenance_text(source, upstream_path, target, sha, kind_label),
                    )
        else:
            spec["selected"] = []
            spec["with_skill"] = []
            owned.append(spec["to"])
            if tree_digest(local) != tree_digest(upstream):
                changed.append(f"{label}/ (support tree)")
            if apply:
                if local.exists():
                    shutil.rmtree(local)
                _copy_tree(upstream, local, file_include=spec.get("file_include"))
                _write(
                    local / "PROVENANCE.md",
                    provenance_text(
                        source,
                        spec["from"] or ".",
                        local,
                        sha,
                        "support files, linked to by the skills",
                    ),
                )

    # Anything the previous run owned and this one does not is deleted. Ownership
    # is read from the record on disk, never inferred from sibling directories.
    previously = read_ownership(dest_root)
    orphans = [p for p in previously if p not in owned]
    for orphan in sorted(orphans):
        target = resolve_under(dest_root, orphan, "previously owned path", sid)
        if target.exists():
            removed.append(f"{orphan} (no longer in the manifest)")
            if apply:
                shutil.rmtree(target)

    all_skills = [n for spec in plan for n in spec.get("with_skill", [])]
    all_selected = [n for spec in plan for n in spec.get("selected", [])]
    missing_mandatory = [m for m in (source.get("mandatory") or []) if m not in all_selected]

    if apply:
        lic = source.get("license_path")
        if not lic:
            _fail(f"[{sid}] `license_path` is required: a redistributed licence must be copied")
        if not (checkout / lic).exists():
            _fail(f"[{sid}] declared license_path `{lic}` not found upstream")
        _write(
            dest_root / "LICENSE.upstream",
            f"Vendored from {source['repo']} at commit {sha}.\n"
            f"Original licence text follows, unmodified.\n"
            f"{'-' * 76}\n\n" + (checkout / lic).read_text(encoding="utf-8"),
        )
        for entry in source.get("additional_licenses") or []:
            src_file = checkout / entry["upstream_license_file"]
            if not src_file.exists():
                _fail(f"[{sid}] additional licence file `{entry['upstream_license_file']}` not found")
            shutil.copy2(src_file, dest_root / entry["license_file"], follow_symlinks=False)
        _write(dest_root / "ATTRIBUTION.md", attribution_text(source, sha, plan))
        write_ownership(dest_root, owned, sid)

    return {
        "id": sid,
        "dest": source["dest"],
        "pinned_commit": source.get("pinned_commit"),
        "upstream_commit": sha,
        "commit_moved": source.get("pinned_commit") != sha,
        "skills": len(all_skills),
        "selected_directories": len(all_selected),
        "added": sorted(added),
        "removed": sorted(removed),
        "changed": sorted(changed),
        "missing_mandatory": missing_mandatory,
    }


def validate_manifest(manifest: dict) -> list:
    """Offline invariants. Fast enough to gate every pull request.

    Deliberately limited. This proves the tree matches what the manifest claims,
    that provenance and licence copies exist, and that nothing excluded slipped
    back in. It does not and cannot prove that an upstream had the right to
    license what it published, or that a declared author is the real one. Do not
    describe it as licence verification.
    """
    problems = []
    seen_ids, seen_dests = set(), set()

    for src in manifest.get("sources", []):
        sid = src.get("id", "<missing id>")
        for field in (
            "id",
            "name",
            "repo",
            "author",
            "license",
            "license_path",
            "dest",
            "pinned_commit",
            "paths",
        ):
            if not src.get(field):
                problems.append(f"[{sid}] source is missing required field `{field}`")
        if sid in seen_ids:
            problems.append(f"[{sid}] duplicate manifest source id")
        seen_ids.add(sid)

        dest = (src.get("dest") or "").strip("/")
        if dest in seen_dests:
            problems.append(f"[{sid}] two sources vendor into the same dest `{dest}`")
        seen_dests.add(dest)

        sha = src.get("pinned_commit", "")
        if sha and not SHA_RE.match(sha):
            problems.append(f"[{sid}] pinned_commit must be a full 40-char sha, got `{sha}`")

        dest_root = REPO_ROOT / dest
        if not dest_root.is_dir():
            problems.append(f"[{sid}] dest `{dest}` does not exist; run --sync")
            continue
        for required in ("ATTRIBUTION.md", "LICENSE.upstream", OWNERSHIP_FILE):
            if not (dest_root / required).exists():
                problems.append(f"[{sid}] `{dest}/{required}` is missing; run --sync")
        for entry in src.get("additional_licenses") or []:
            if not (dest_root / entry.get("license_file", "")).exists():
                problems.append(
                    f"[{sid}] additional licence text `{dest}/{entry.get('license_file')}` is "
                    f"missing, but the manifest says files here are under {entry.get('license')}"
                )

        if not src.get("paths"):
            continue
        specs = path_specs(src)
        skills_found = []
        expected_owned = set()
        for spec in specs:
            local = dest_root / spec["to"] if spec["to"] else dest_root
            for name in spec.get("exclude") or []:
                if name not in (spec.get("exclude_reasons") or {}):
                    problems.append(
                        f"[{sid}] `{spec['from']}/{name}` is excluded with no reason recorded"
                    )
            for name in spec.get("exclude_reasons") or {}:
                if name not in (spec.get("exclude") or []):
                    problems.append(
                        f"[{sid}] exclude_reasons documents `{name}` but exclude omits it"
                    )
            if not local.is_dir():
                problems.append(f"[{sid}] mapped path `{dest}/{spec['to']}` missing; run --sync")
                continue

            if spec["kind"] == SKILL_COLLECTION:
                for name in _child_dirs(local):
                    child = local / name
                    expected_owned.add(posixpath.join(spec["to"], name) if spec["to"] else name)
                    if _has_skill(child):
                        skills_found.append(name)
                        if not (child / "PROVENANCE.md").exists():
                            problems.append(
                                f"[{sid}] `{dest}/{spec['to']}/{name}` has no PROVENANCE.md; run --sync"
                            )
                    if any(fnmatch.fnmatch(name, p) for p in spec.get("exclude", [])):
                        problems.append(
                            f"[{sid}] `{dest}/{spec['to']}/{name}` is present but excluded"
                        )
            else:
                expected_owned.add(spec["to"])
                if not (local / "PROVENANCE.md").exists():
                    problems.append(
                        f"[{sid}] support tree `{dest}/{spec['to']}` has no PROVENANCE.md; run --sync"
                    )

        recorded = set(read_ownership(dest_root))
        for stale in sorted(recorded - expected_owned):
            problems.append(
                f"[{sid}] `{dest}/{OWNERSHIP_FILE}` still claims `{stale}`, which the manifest no "
                f"longer maps; run --sync to remove it"
            )
        for unrecorded in sorted(expected_owned - recorded):
            problems.append(
                f"[{sid}] `{dest}/{unrecorded}` is present but not recorded as owned; run --sync"
            )

        for name in src.get("mandatory") or []:
            if name not in skills_found:
                problems.append(f"[{sid}] mandatory skill `{name}` is not vendored into `{dest}`")

    if not NOTICES_PATH.exists():
        problems.append("THIRD_PARTY_NOTICES.md is missing; run --sync")
    else:
        notices = NOTICES_PATH.read_text(encoding="utf-8")
        for src in manifest.get("sources", []):
            if src.get("pinned_commit") and src["pinned_commit"] not in notices:
                problems.append(
                    f"[{src.get('id')}] THIRD_PARTY_NOTICES.md does not cite the pinned commit; run --sync"
                )
    return problems


def main(argv: list) -> int:
    ap = argparse.ArgumentParser(description="Import and refresh vendored upstream content.")
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--validate-manifest",
        action="store_true",
        help="offline check that the tree still matches the manifest",
    )
    mode.add_argument("--check", action="store_true", help="report upstream drift, write nothing")
    mode.add_argument("--sync", action="store_true", help="apply upstream into the working tree")
    ap.add_argument("--source", action="append", help="limit to a manifest source id (repeatable)")
    ap.add_argument("--output", choices=("text", "json"), default="text")
    args = ap.parse_args(argv)

    manifest = load_manifest()

    if args.validate_manifest:
        problems = validate_manifest(manifest)
        if args.output == "json":
            print(json.dumps({"ok": not problems, "problems": problems}, indent=2))
        else:
            for problem in problems:
                print(f"error: {problem}")
            print()
            print(
                f"{len(manifest.get('sources', []))} vendored source(s) checked, "
                f"{len(problems)} problem(s)"
            )
        return 1 if problems else 0

    if not shutil.which("git"):
        _fail("git is required and was not found on PATH")

    sources = manifest.get("sources", [])
    if args.source:
        sources = [s for s in sources if s["id"] in args.source]
        if not sources:
            _fail(f"no manifest source matched {args.source}")
    if not sources:
        _fail("manifest declares no sources")

    results = []
    with tempfile.TemporaryDirectory(prefix="vendor-sync-") as tmp:
        for source in sources:
            checkout, sha = fetch_upstream(source, Path(tmp))
            results.append(process_source(source, checkout, sha, apply=args.sync))
            if args.sync:
                source["pinned_commit"] = sha
                source["pinned_at"] = _dt.date.today().isoformat()

    if args.sync:
        MANIFEST_PATH.write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        _write(NOTICES_PATH, notices_text(manifest))

    blocked = [r for r in results if r["missing_mandatory"]]
    drift = [r for r in results if r["added"] or r["removed"] or r["changed"] or r["commit_moved"]]

    if args.output == "json":
        print(
            json.dumps(
                {
                    "mode": "sync" if args.sync else "check",
                    "drift": bool(drift),
                    "blocked": bool(blocked),
                    "sources": results,
                },
                indent=2,
            )
        )
    else:
        for r in results:
            print(f"[{r['id']}] -> {r['dest']}")
            print(
                f"  upstream commit    : {r['upstream_commit'][:12]}"
                + ("  (moved)" if r["commit_moved"] else "  (unchanged)")
            )
            print(
                f"  skills             : {r['skills']}"
                f"   (from {r['selected_directories']} selected directories)"
            )
            for key in ("added", "removed", "changed"):
                if r[key]:
                    print(f"  {key:<18} : {', '.join(r[key])}")
            if r["missing_mandatory"]:
                print(f"  MANDATORY MISSING  : {', '.join(r['missing_mandatory'])}")
        print()
        if args.sync:
            print("drift applied" if drift else "nothing to apply")
        else:
            print("drift detected" if drift else "no drift detected")

    if blocked:
        print(
            "error: a skill listed as mandatory is absent from the selection; "
            "fix include/exclude in skills/vendor.manifest.json",
            file=sys.stderr,
        )
        return 1
    if args.check and drift:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
