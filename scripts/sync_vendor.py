# ----------------------------------------------------------------------- core


def process_source(source: dict, checkout: Path, sha: str, apply: bool) -> dict:
    sub = source.get("source_subpath", "").strip("/")
    upstream_root = checkout / sub if sub else checkout
    if not upstream_root.is_dir():
        _fail(f"[{source['id']}] upstream subpath not found: {sub or '<root>'}")

    upstream_names = sorted(
        d.name for d in upstream_root.iterdir() if d.is_dir() and not d.name.startswith(".")
    )
    selected = _selected(upstream_names, source.get("include", ["*"]), source.get("exclude", []))

    missing_mandatory = [m for m in (source.get("mandatory") or []) if m not in selected]

    dest_root = REPO_ROOT / source["dest"]
    existing = sorted(
        d.name
        for d in (dest_root.iterdir() if dest_root.is_dir() else [])
        if d.is_dir() and not d.name.startswith(".")
    )

    added = [n for n in selected if n not in existing]
    removed = [n for n in existing if n not in selected]
    changed = []
    for name in selected:
        if name in existing and tree_digest(dest_root / name) != tree_digest(upstream_root / name):
            changed.append(name)

    written = []
    if apply:
        for name in removed:
            shutil.rmtree(dest_root / name)
        for name in selected:
            target = dest_root / name
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(upstream_root / name, target, ignore=shutil.ignore_patterns(".git"))
            if _write(target / "PROVENANCE.md", provenance_text(source, name, sha)):
                written.append(str((target / "PROVENANCE.md").relative_to(REPO_ROOT)))

        lic_rel = source.get("license_path")
        if lic_rel and (checkout / lic_rel).exists():
            header = (
                f"Vendored from {source['repo']} at commit {sha}.\n"
                f"Original licence text follows, unmodified.\n"
                f"{'-' * 76}\n\n"
            )
            _write(
                dest_root / "LICENSE.upstream",
                header + (checkout / lic_rel).read_text(encoding="utf-8"),
            )

        _write(
            dest_root / "ATTRIBUTION.md",
            attribution_text(source, sha, selected, source.get("exclude_reasons", {})),
        )

    return {
        "id": source["id"],
        "dest": source["dest"],
        "pinned_commit": source.get("pinned_commit"),
        "upstream_commit": sha,
        "commit_moved": source.get("pinned_commit") != sha,
        "upstream_skill_count": len(upstream_names),
        "selected_count": len(selected),
        "added": added,
        "removed": removed,
        "changed": changed,
        "missing_mandatory": missing_mandatory,
        "generated": written,
    }


SHA_RE = re.compile(r"^[0-9a-f]{40}$")


def validate_manifest(manifest: dict) -> list:
    """Offline invariants. Fast enough to gate every pull request.

    Answers the question a reviewer actually has: does the tree still match what
    the manifest claims about it? No network, so an upstream commit moving does
    not turn every unrelated pull request red.
    """
    problems = []
    seen_ids, seen_dests = set(), set()

    for src in manifest.get("sources", []):
        sid = src.get("id", "<missing id>")
        for field in ("id", "name", "repo", "license", "dest", "pinned_commit"):
            if not src.get(field):
                problems.append(f"[{sid}] source is missing required field `{field}`")
        if sid in seen_ids:
            problems.append(f"[{sid}] duplicate manifest source id")
        seen_ids.add(sid)

        dest = (src.get("dest") or "").strip("/")
        if dest in seen_dests:
            problems.append(f"[{sid}] two sources vendor into the same dest `{dest}`")
        seen_dests.add(dest)

        sha = src.get("pinned_commit", "")
        if sha and not SHA_RE.match(sha):
            problems.append(f"[{sid}] pinned_commit must be a full 40-char sha, got `{sha}`")

        for name in src.get("exclude") or []:
            if name not in (src.get("exclude_reasons") or {}):
                problems.append(f"[{sid}] `{name}` is excluded with no reason in exclude_reasons")
        for name in src.get("exclude_reasons") or {}:
            if name not in (src.get("exclude") or []):
                problems.append(f"[{sid}] exclude_reasons documents `{name}` but exclude omits it")

        dest_root = REPO_ROOT / dest
        if not dest_root.is_dir():
            problems.append(f"[{sid}] dest `{dest}` does not exist; run --sync")
            continue

        for required in ("ATTRIBUTION.md", "LICENSE.upstream"):
            if not (dest_root / required).exists():
                problems.append(f"[{sid}] `{dest}/{required}` is missing; run --sync")

        present = sorted(
            d.name for d in dest_root.iterdir() if d.is_dir() and not d.name.startswith(".")
        )
        for name in present:
            if not (dest_root / name / "PROVENANCE.md").exists():
                problems.append(f"[{sid}] `{dest}/{name}` has no PROVENANCE.md; run --sync")
            if any(fnmatch.fnmatch(name, pat) for pat in src.get("exclude", [])):
                problems.append(f"[{sid}] `{dest}/{name}` is present but the manifest excludes it")
        for name in src.get("mandatory") or []:
            if name not in present:
                problems.append(f"[{sid}] mandatory skill `{name}` is not vendored into `{dest}`")

    if not NOTICES_PATH.exists():
        problems.append("THIRD_PARTY_NOTICES.md is missing; run --sync")
    else:
        notices = NOTICES_PATH.read_text(encoding="utf-8")
        for src in manifest.get("sources", []):
            if src.get("pinned_commit") and src["pinned_commit"] not in notices:
                problems.append(
                    f"[{src.get('id')}] THIRD_PARTY_NOTICES.md does not cite the pinned commit; run --sync"
                )
    return problems


def main(argv: list) -> int:
    ap = argparse.ArgumentParser(description="Import and refresh vendored upstream skills.")
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--validate-manifest",
        action="store_true",
        help="offline check that the tree still matches the manifest",
    )
    mode.add_argument("--check", action="store_true", help="report upstream drift, write nothing")
    mode.add_argument("--sync", action="store_true", help="apply upstream into the working tree")
    ap.add_argument("--source", action="append", help="limit to a manifest source id (repeatable)")
    ap.add_argument("--output", choices=("text", "json"), default="text")
    args = ap.parse_args(argv)

    if args.validate_manifest:
        manifest = load_manifest()
        problems = validate_manifest(manifest)
        if args.output == "json":
            print(json.dumps({"ok": not problems, "problems": problems}, indent=2))
        else:
            for problem in problems:
                print(f"error: {problem}")
            print()
            print(
                f"{len(manifest.get('sources', []))} vendored source(s) checked, "
                f"{len(problems)} problem(s)"
            )
        return 1 if problems else 0

    if not shutil.which("git"):
        _fail("git is required and was not found on PATH")

    manifest = load_manifest()
    sources = manifest.get("sources", [])
    if args.source:
        sources = [s for s in sources if s["id"] in args.source]
        if not sources:
            _fail(f"no manifest source matched {args.source}")
    if not sources:
        _fail("manifest declares no sources")

    results = []
    with tempfile.TemporaryDirectory(prefix="vendor-sync-") as tmp:
        workdir = Path(tmp)
        for source in sources:
            checkout, sha = fetch_upstream(source, workdir)
            res = process_source(source, checkout, sha, apply=args.sync)
            if args.sync:
                source["pinned_commit"] = sha
                source["pinned_at"] = _dt.date.today().isoformat()
            results.append(res)

    if args.sync:
        MANIFEST_PATH.write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        _write(NOTICES_PATH, notices_text(manifest))

    blocked = [r for r in results if r["missing_mandatory"]]
    drift = [
        r
        for r in results
        if r["added"] or r["removed"] or r["changed"] or r["commit_moved"]
    ]

    if args.output == "json":
        print(
            json.dumps(
                {
                    "mode": "sync" if args.sync else "check",
                    "drift": bool(drift),
                    "blocked": bool(blocked),
                    "sources": results,
                },
                indent=2,
            )
        )
    else:
        for r in results:
            print(f"[{r['id']}] -> {r['dest']}")
            print(f"  upstream commit : {r['upstream_commit'][:12]}"
                  + ("  (moved)" if r["commit_moved"] else "  (unchanged)"))
            print(f"  upstream skills : {r['upstream_skill_count']}  selected: {r['selected_count']}")
            for label, key in (("added", "added"), ("removed", "removed"), ("changed", "changed")):
                if r[key]:
                    print(f"  {label:<15} : {', '.join(r[key])}")
            if r["missing_mandatory"]:
                print(f"  MANDATORY MISSING: {', '.join(r['missing_mandatory'])}")
        verb = "applied" if args.sync else "detected"
        print()
        print(f"{'drift ' + verb if drift else 'no drift ' + ('applied' if args.sync else 'detected')}")

    if blocked:
        print(
            "error: a skill listed as mandatory is absent from the selection; "
            "fix include/exclude in skills/vendor.manifest.json",
            file=sys.stderr,
        )
        return 1
    if args.check and drift:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
