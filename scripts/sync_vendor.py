# --------------------------------------------------------------------------- io


def _fail(msg: str, code: int = 2):
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(code)


def _run(args: list, cwd: "Path | None" = None) -> str:
    proc = subprocess.run(args, cwd=str(cwd) if cwd else None, capture_output=True, text=True)
    if proc.returncode != 0:
        _fail(f"command failed: {' '.join(args)}\n{proc.stderr.strip()}")
    return proc.stdout.strip()


def load_manifest() -> dict:
    if not MANIFEST_PATH.exists():
        _fail(f"missing manifest: {MANIFEST_PATH}")
    try:
        return json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        _fail(f"manifest is not valid JSON: {exc}")


def _write(path: Path, text: str) -> bool:
    """Write only when content changes. Returns True when the file changed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def _rel(from_dir: Path, to_path: Path) -> str:
    """Markdown-safe relative link between two paths inside the repository."""
    return os.path.relpath(to_path, from_dir).replace(os.sep, "/")


# ------------------------------------------------------------------- path safety


def safe_segment(value: str, label: str, source_id: str) -> str:
    """A manifest-supplied path fragment, validated before it touches the disk.

    A manifest is data, and this script writes and deletes based on it, so the
    data is treated as untrusted. `dest: ../../etc` used to escape the repository
    root entirely.
    """
    raw = (value or "").strip()
    if not raw:
        return ""
    # Absoluteness is checked before any stripping. Testing it afterwards was a
    # bug in the first version of this guard: `/etc` became `etc` and passed.
    if (
        raw.startswith("/")
        or raw.startswith("\\")
        or Path(raw).is_absolute()
        or re.match(r"^[A-Za-z]:", raw)
    ):
        _fail(f"[{source_id}] `{label}` must be a repository-relative path, got `{value}`")
    cleaned = raw.strip("/")
    if not cleaned:
        return ""
    parts = [p for p in cleaned.replace("\\", "/").split("/")]
    for part in parts:
        if part in ("", ".", ".."):
            _fail(
                f"[{source_id}] `{label}` may not contain empty, `.` or `..` segments, got `{value}`"
            )
    return "/".join(parts)


def resolve_under(root: Path, relative: str, label: str, source_id: str) -> Path:
    """Join and prove the result stays inside `root`."""
    target = (root / relative).resolve() if relative else root.resolve()
    root_resolved = root.resolve()
    if target != root_resolved and root_resolved not in target.parents:
        _fail(f"[{source_id}] `{label}` resolves outside {root_resolved}: {target}")
    return target


def assert_no_symlinks(root: Path, source_id: str, upstream_label: str) -> None:
    """Refuse an upstream tree containing any symlink.

    Following one lets a moving upstream read an arbitrary runner path and have
    its contents committed to a public pull request.
    """
    if root.is_symlink():
        _fail(f"[{source_id}] upstream `{upstream_label}` is a symlink; refusing to vendor it")
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        for name in list(dirnames) + list(filenames):
            candidate = Path(dirpath) / name
            if candidate.is_symlink():
                shown = candidate.relative_to(root).as_posix()
                _fail(
                    f"[{source_id}] upstream `{upstream_label}` contains a symlink at `{shown}` "
                    f"-> `{os.readlink(candidate)}`. Symlinks are never vendored: following one "
                    f"would let upstream publish the contents of an arbitrary runner path. "
                    f"Exclude the path in the manifest or raise it with upstream."
                )


# ---------------------------------------------------------------- fingerprints


def tree_digest(root: Path) -> str:
    """Order-stable digest of a directory tree.

    Hashes entry type, relative path, executable bit and content, and records
    empty directories. An earlier version hashed only file path and content, so a
    chmod, an added empty directory, or a symlink replacing a file with identical
    bytes were all invisible to drift detection.

    Files this repository generates are excluded. Including them would make every
    vendored tree look permanently different from its upstream.
    """
    if not root.exists():
        return ""
    entries = []
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        dirnames[:] = sorted(d for d in dirnames if d != ".git")
        here = Path(dirpath)
        if not dirnames and not filenames:
            entries.append(("d", here.relative_to(root).as_posix(), "", ""))
        for name in sorted(filenames):
            if name in GENERATED_NAMES:
                continue
            full = here / name
            rel = full.relative_to(root).as_posix()
            if full.is_symlink():
                entries.append(("l", rel, "", os.readlink(full)))
                continue
            mode = "x" if os.stat(full).st_mode & stat.S_IXUSR else "-"
            entries.append(("f", rel, mode, hashlib.sha256(full.read_bytes()).hexdigest()))
    digest = hashlib.sha256()
    for kind, rel, mode, payload in sorted(entries):
        digest.update(f"{kind}\0{rel}\0{mode}\0{payload}\n".encode("utf-8"))
    return digest.hexdigest()


def _selected(names: list, include, exclude: list) -> list:
    """Apply include and exclude globs.

    `include` absent means everything. `include: []` means nothing, which is what
    a maintainer disabling a mapping writes. Conflating the two was a fail-open.
    """
    patterns = ["*"] if include is None else list(include)
    keep = []
    for name in sorted(names):
        if not any(fnmatch.fnmatch(name, pat) for pat in patterns):
            continue
        if any(fnmatch.fnmatch(name, pat) for pat in exclude or []):
            continue
        keep.append(name)
    return keep


def _child_dirs(root: Path) -> list:
    if not root.is_dir():
        return []
    return sorted(d.name for d in root.iterdir() if d.is_dir() and not d.name.startswith("."))


def _has_skill(path: Path) -> bool:
    return (path / "SKILL.md").is_file()


def _copy_tree(src: Path, dst: Path, file_include=None) -> None:
    """Copy without following symlinks. Optionally filter files by glob."""
    for dirpath, dirnames, filenames in os.walk(src, followlinks=False):
        dirnames[:] = sorted(d for d in dirnames if d != ".git")
        rel = Path(dirpath).relative_to(src)
        for name in sorted(filenames):
            if file_include is not None and not any(
                fnmatch.fnmatch(name, pat) or fnmatch.fnmatch((rel / name).as_posix(), pat)
                for pat in file_include
            ):
                continue
            target = dst / rel / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(Path(dirpath) / name, target, follow_symlinks=False)
        if file_include is None:
            (dst / rel).mkdir(parents=True, exist_ok=True)


# ------------------------------------------------------------------- ownership


def read_ownership(dest_root: Path) -> list:
    path = dest_root / OWNERSHIP_FILE
    if not path.exists():
        return []
    try:
        return sorted(set(json.loads(path.read_text(encoding="utf-8")).get("paths", [])))
    except (json.JSONDecodeError, AttributeError):
        return []


def write_ownership(dest_root: Path, owned: list, source_id: str) -> None:
    _write(
        dest_root / OWNERSHIP_FILE,
        json.dumps(
            {
                "$comment": (
                    "Written by scripts/sync_vendor.py. Lists exactly what the last sync placed "
                    "in this directory, so the next sync can delete what it no longer owns "
                    "without inferring ownership from whatever happens to be here. Do not edit."
                ),
                "source": source_id,
                "paths": sorted(set(owned)),
            },
            indent=2,
        )
        + "\n",
    )


# ------------------------------------------------------------------- upstream


def fetch_upstream(source: dict, workdir: Path) -> "tuple[Path, str]":
    ref = source.get("ref") or "HEAD"
    dest = workdir / source["id"]
    _run(["git", "clone", "--quiet", "--depth", "1", "--branch", ref, source["repo"], str(dest)])
    return dest, _run(["git", "rev-parse", "HEAD"], cwd=dest)


