#!/usr/bin/env python3
"""Import and refresh vendored upstream skills.

One code path serves both jobs. The first import of an upstream project and the
scheduled refresh two weeks later run exactly the same function, so a vendored
directory cannot drift into a hand-maintained fork by accident.

Reads skills/vendor.manifest.json. Standard library only.

    scripts/sync_vendor.py --validate-manifest  # offline consistency check, used by CI
    scripts/sync_vendor.py --check              # report drift vs upstream, write nothing
    scripts/sync_vendor.py --sync               # apply upstream into the tree
    scripts/sync_vendor.py --sync --source pstack
    scripts/sync_vendor.py --check --output json

--validate-manifest needs no network, so it can gate every pull request. --check
and --sync clone upstream and belong in the scheduled refresh, where an upstream
commit moving is news rather than a broken build.

## Why a source declares `paths` rather than one subdirectory

The first vendored project kept everything under `skills/`. The second,
job-hunt-skills, has 47 links from its skills into a sibling `guides/` directory
and more into `templates/`. Copying only `skills/` produces a tree whose internal
links all point at nothing.

So a source maps a list of upstream subtrees into its own vendored root, and the
mapping preserves the relative distance between them. Two kinds:

    skill-collection  a directory of skill directories. Each selected child is
                      tracked individually, gets a PROVENANCE.md, and appears in
                      the added/removed/changed report.
    support           a subtree the skills link into. Copied whole, one
                      PROVENANCE.md at its root, no per-file tracking.

Exit codes
    0  no drift (--check), sync applied cleanly (--sync), or manifest consistent
    1  drift detected, inconsistent manifest, or a mandatory skill is missing
    2  usage or environment error
"""

from __future__ import annotations

import argparse
import datetime as _dt
import fnmatch
import hashlib
import json
import os
import posixpath
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = REPO_ROOT / "skills" / "vendor.manifest.json"
NOTICES_PATH = REPO_ROOT / "THIRD_PARTY_NOTICES.md"
GENERATED_BANNER = "<!-- generated by scripts/sync_vendor.py -- do not edit by hand -->"
SHA_RE = re.compile(r"^[0-9a-f]{40}$")
SKILL_COLLECTION = "skill-collection"
SUPPORT = "support"


# --------------------------------------------------------------------------- io


def _fail(msg: str, code: int = 2):
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(code)


def _run(args: list, cwd: "Path | None" = None) -> str:
    proc = subprocess.run(args, cwd=str(cwd) if cwd else None, capture_output=True, text=True)
    if proc.returncode != 0:
        _fail(f"command failed: {' '.join(args)}\n{proc.stderr.strip()}")
    return proc.stdout.strip()


def load_manifest() -> dict:
    if not MANIFEST_PATH.exists():
        _fail(f"missing manifest: {MANIFEST_PATH}")
    try:
        return json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        _fail(f"manifest is not valid JSON: {exc}")


def _write(path: Path, text: str) -> bool:
    """Write only when content changes. Returns True when the file changed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def _rel(from_dir: Path, to_path: Path) -> str:
    """Markdown-safe relative link between two paths inside the repository."""
    return os.path.relpath(to_path, from_dir).replace(os.sep, "/")


# ---------------------------------------------------------------- fingerprints


def tree_digest(root: Path) -> str:
    """Order-stable digest of a directory's content.

    PROVENANCE.md is excluded because this repository generates it. Including it
    would make every vendored tree look permanently different from upstream.
    """
    if not root.exists():
        return ""
    entries = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d != ".git")
        for name in sorted(filenames):
            if name == "PROVENANCE.md":
                continue
            full = Path(dirpath) / name
            rel = full.relative_to(root).as_posix()
            entries.append((rel, hashlib.sha256(full.read_bytes()).hexdigest()))
    digest = hashlib.sha256()
    for rel, file_hash in sorted(entries):
        digest.update(rel.encode("utf-8") + b"\0" + file_hash.encode("ascii") + b"\n")
    return digest.hexdigest()


def _selected(names: list, include: list, exclude: list) -> list:
    keep = []
    for name in sorted(names):
        if not any(fnmatch.fnmatch(name, pat) for pat in include or ["*"]):
            continue
        if any(fnmatch.fnmatch(name, pat) for pat in exclude or []):
            continue
        keep.append(name)
    return keep


def _child_dirs(root: Path) -> list:
    if not root.is_dir():
        return []
    return sorted(d.name for d in root.iterdir() if d.is_dir() and not d.name.startswith("."))


def _has_skill(path: Path) -> bool:
    return (path / "SKILL.md").is_file()


# ------------------------------------------------------------------- upstream


def fetch_upstream(source: dict, workdir: Path) -> "tuple[Path, str]":
    ref = source.get("ref") or "HEAD"
    dest = workdir / source["id"]
    _run(
        ["git", "clone", "--quiet", "--depth", "1", "--branch", ref, source["repo"], str(dest)]
    )
    return dest, _run(["git", "rev-parse", "HEAD"], cwd=dest)


# ------------------------------------------------------------------ rendering


def provenance_text(source: dict, upstream_path: str, local_dir: Path, sha: str, kind: str) -> str:
    repo = source["repo"].rstrip("/")
    dest_root = REPO_ROOT / source["dest"]
    permalink = f"{repo}/tree/{sha}/{upstream_path}"
    label = local_dir.name

    rows = [
        f"| Upstream project | [{source['name']}]({repo}) |",
        f"| Upstream path | `{upstream_path}` |",
        f"| Pinned commit | [`{sha[:12]}`]({repo}/commit/{sha}) |",
        f"| Permalink | {permalink} |",
        f"| Original author | {source.get('author', 'see upstream')} |",
        f"| Upstream licence | {source.get('license', 'see upstream')} |",
        f"| Licence copy | [`{_rel(local_dir, dest_root / 'LICENSE.upstream')}`]"
        f"({_rel(local_dir, dest_root / 'LICENSE.upstream')}) |",
        f"| Full attribution | [`{_rel(local_dir, dest_root / 'ATTRIBUTION.md')}`]"
        f"({_rel(local_dir, dest_root / 'ATTRIBUTION.md')}) |",
        f"| Content kind | {kind} |",
        "| Refresh cadence | Automated every two weeks by "
        f"[`{_rel(local_dir, REPO_ROOT / '.github/workflows/sync-vendored-skills.yml')}`]"
        f"({_rel(local_dir, REPO_ROOT / '.github/workflows/sync-vendored-skills.yml')}) |",
    ]
    if source.get("upstream_of_upstream"):
        rows.append(f"| Upstream's own source | {source['upstream_of_upstream']} |")

    manifest_link = _rel(local_dir, MANIFEST_PATH)
    return "\n".join(
        [
            GENERATED_BANNER,
            "",
            f"# Provenance: `{label}`",
            "",
            "This directory is vendored, unmodified, from an upstream project. Do not edit it here.",
            "",
            "| Field | Value |",
            "| --- | --- |",
            *rows,
            "",
            "## Changing this",
            "",
            "Send the change to the upstream project. If this repository must diverge, remove the",
            f"entry from [`{manifest_link}`]({manifest_link}), copy it to a non-vendored path, and",
            "record why in the collection's `ATTRIBUTION.md`. Local edits made in place are silently",
            "reverted by the next scheduled sync.",
            "",
        ]
    )


def attribution_text(source: dict, sha: str, plan: list) -> str:
    repo = source["repo"].rstrip("/")
    dest_root = REPO_ROOT / source["dest"]
    out = [
        GENERATED_BANNER,
        "",
        f"# Attribution: {source['name']}",
        "",
        f"Everything in this directory was copied from [{source['name']}]({repo}) at commit",
        f"[`{sha}`]({repo}/commit/{sha}), pinned on {source.get('pinned_at', 'n/a')}.",
        "",
        f"- **Upstream project:** <{repo}>",
        f"- **Original author:** {source.get('author', 'see upstream')}",
        f"- **Upstream licence:** {source.get('license', 'see upstream')}, reproduced verbatim in "
        "[`LICENSE.upstream`](./LICENSE.upstream)",
        f"- **Tracked by:** [`{_rel(dest_root, MANIFEST_PATH)}`]({_rel(dest_root, MANIFEST_PATH)})",
        "- **Refreshed by:** "
        f"[`{_rel(dest_root, REPO_ROOT / 'scripts/sync_vendor.py')}`]"
        f"({_rel(dest_root, REPO_ROOT / 'scripts/sync_vendor.py')}), run every two weeks by "
        f"[`{_rel(dest_root, REPO_ROOT / '.github/workflows/sync-vendored-skills.yml')}`]"
        f"({_rel(dest_root, REPO_ROOT / '.github/workflows/sync-vendored-skills.yml')})",
    ]
    if source.get("upstream_of_upstream"):
        out.append(f"- **Upstream's own source:** {source['upstream_of_upstream']}")
    out += [
        "",
        "No functional changes were made to the vendored content. This repository adds only a",
        "`PROVENANCE.md` per vendored directory and this file.",
        "",
        "## Layout",
        "",
        "Upstream subtrees are mapped so that the relative links inside them keep resolving.",
        "",
        "| Upstream path | Vendored to | Kind |",
        "| --- | --- | --- |",
    ]
    for spec in plan:
        out.append(
            f"| `{spec['from'] or '.'}` | [`{spec['to'] or '.'}/`](./{spec['to']}/) | {spec['kind']} |"
        )

    for spec in plan:
        if spec["kind"] != SKILL_COLLECTION:
            continue
        out += [
            "",
            f"## Imported skills from `{spec['from']}` ({len(spec['selected'])})",
            "",
            "| Skill | Upstream permalink |",
            "| --- | --- |",
        ]
        for name in spec["selected"]:
            upstream_path = posixpath.join(spec["from"], name) if spec["from"] else name
            local = posixpath.join(spec["to"], name) if spec["to"] else name
            out.append(
                f"| [`{name}`](./{local}/) | [`{upstream_path}`]({repo}/tree/{sha}/{upstream_path}) |"
            )

    mandatory = source.get("mandatory") or []
    if mandatory:
        out += ["", "## Mandatory imports", "", source.get("mandatory_reason", ""), ""]
        for name in mandatory:
            out.append(f"- `{name}`")

    reasons = {}
    for spec in plan:
        reasons.update(spec.get("exclude_reasons") or {})
    if reasons:
        out += [
            "",
            "## Deliberate exclusions",
            "",
            "Upstream content left out of this repository, and why. Recorded so the decision is",
            "auditable rather than looking like an incomplete import.",
            "",
            "| Upstream path | Reason |",
            "| --- | --- |",
        ]
        for name in sorted(reasons):
            out.append(f"| `{name}` | {reasons[name]} |")

    if source.get("limitations"):
        out += ["", "## Known limitations of this import", ""]
        for item in source["limitations"]:
            out.append(f"- {item}")

    if source.get("notes"):
        out += ["", "## Notes", "", source["notes"]]
    out.append("")
    return "\n".join(out)


