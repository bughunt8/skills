#!/usr/bin/env python3
"""Import and refresh vendored upstream skills.

One code path serves both jobs. The first import of an upstream project and the
scheduled refresh two weeks later run exactly the same function, so a vendored
directory can never drift into a hand-maintained fork by accident.

Reads skills/vendor.manifest.json. Standard library only.

    scripts/sync_vendor.py --validate-manifest  # offline consistency check, used by CI
    scripts/sync_vendor.py --check              # report drift vs upstream, write nothing
    scripts/sync_vendor.py --sync               # apply upstream into the tree
    scripts/sync_vendor.py --sync --source pstack
    scripts/sync_vendor.py --check --output json

--validate-manifest needs no network, so it can gate every pull request. --check
and --sync clone upstream and belong in the scheduled refresh, where an upstream
commit moving is news rather than a broken build.

Exit codes
    0  no drift (--check), sync applied cleanly (--sync), or manifest consistent
    1  drift detected, inconsistent manifest, or a mandatory skill is missing
    2  usage or environment error
"""

from __future__ import annotations

import argparse
import datetime as _dt
import fnmatch
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = REPO_ROOT / "skills" / "vendor.manifest.json"
NOTICES_PATH = REPO_ROOT / "THIRD_PARTY_NOTICES.md"
GENERATED_BANNER = "<!-- generated by scripts/sync_vendor.py -- do not edit by hand -->"


# --------------------------------------------------------------------------- io


def _fail(msg: str, code: int = 2) -> "None":
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(code)


def _run(args: list, cwd: "Path | None" = None) -> str:
    proc = subprocess.run(
        args, cwd=str(cwd) if cwd else None, capture_output=True, text=True
    )
    if proc.returncode != 0:
        _fail(f"command failed: {' '.join(args)}\n{proc.stderr.strip()}")
    return proc.stdout.strip()


def load_manifest() -> dict:
    if not MANIFEST_PATH.exists():
        _fail(f"missing manifest: {MANIFEST_PATH}")
    try:
        return json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        _fail(f"manifest is not valid JSON: {exc}")


def _write(path: Path, text: str) -> bool:
    """Write only when content changes. Returns True when the file changed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


# ---------------------------------------------------------------- fingerprints


def tree_digest(root: Path) -> str:
    """Order-stable digest of a directory's tracked content.

    Provenance and attribution files are excluded because this repository
    generates them; including them would make every tree look permanently
    dirty against upstream.
    """
    if not root.exists():
        return ""
    generated = {"PROVENANCE.md"}
    entries = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d != ".git")
        for name in sorted(filenames):
            if name in generated:
                continue
            full = Path(dirpath) / name
            rel = full.relative_to(root).as_posix()
            entries.append((rel, hashlib.sha256(full.read_bytes()).hexdigest()))
    h = hashlib.sha256()
    for rel, digest in sorted(entries):
        h.update(rel.encode("utf-8") + b"\0" + digest.encode("ascii") + b"\n")
    return h.hexdigest()


def _selected(names: list, include: list, exclude: list) -> list:
    keep = []
    for name in sorted(names):
        if not any(fnmatch.fnmatch(name, pat) for pat in include or ["*"]):
            continue
        if any(fnmatch.fnmatch(name, pat) for pat in exclude or []):
            continue
        keep.append(name)
    return keep


# ------------------------------------------------------------------- upstream


def fetch_upstream(source: dict, workdir: Path) -> "tuple[Path, str]":
    """Clone the upstream repo at the manifest ref. Returns (checkout, sha)."""
    ref = source.get("ref") or "HEAD"
    dest = workdir / source["id"]
    _run(["git", "clone", "--quiet", "--depth", "1", "--branch", ref, source["repo"], str(dest)])
    sha = _run(["git", "rev-parse", "HEAD"], cwd=dest)
    return dest, sha


# ------------------------------------------------------------------ rendering


def provenance_text(source: dict, skill: str, sha: str) -> str:
    repo = source["repo"].rstrip("/")
    sub = source.get("source_subpath", "").strip("/")
    upstream_path = f"{sub}/{skill}" if sub else skill
    permalink = f"{repo}/tree/{sha}/{upstream_path}"
    lines = [
        GENERATED_BANNER,
        "",
        f"# Provenance: `{skill}`",
        "",
        f"This directory is vendored, unmodified, from an upstream project. Do not edit it here.",
        "",
        f"| Field | Value |",
        f"| --- | --- |",
        f"| Upstream project | [{source['name']}]({repo}) |",
        f"| Upstream path | `{upstream_path}` |",
        f"| Pinned commit | [`{sha[:12]}`]({repo}/commit/{sha}) |",
        f"| Permalink | {permalink} |",
        f"| Original author | {source.get('author', 'see upstream')} |",
        f"| Upstream licence | {source.get('license', 'see upstream')} |",
        f"| Licence copy | [`../LICENSE.upstream`](../LICENSE.upstream) |",
        f"| Full attribution | [`../ATTRIBUTION.md`](../ATTRIBUTION.md) |",
        f"| Refresh cadence | Automated every two weeks by [`.github/workflows/sync-vendored-skills.yml`](../../../.github/workflows/sync-vendored-skills.yml) |",
    ]
    if source.get("upstream_of_upstream"):
        lines.append(
            f"| Upstream's own source | {source['upstream_of_upstream']} |"
        )
    lines += [
        "",
        "## Changing this skill",
        "",
        "Send the change to the upstream project. If this repository must diverge, remove the",
        f"skill from `include` in [`skills/vendor.manifest.json`](../../vendor.manifest.json), copy it to a",
        "non-vendored path, and record why in `ATTRIBUTION.md`. Local edits made in place are",
        "silently reverted by the next scheduled sync.",
        "",
    ]
    return "\n".join(lines)


def attribution_text(source: dict, sha: str, skills: list, excluded: dict) -> str:
    repo = source["repo"].rstrip("/")
    out = [
        GENERATED_BANNER,
        "",
        f"# Attribution: {source['name']}",
        "",
        f"Every skill in this directory was copied from [{source['name']}]({repo}) at commit",
        f"[`{sha}`]({repo}/commit/{sha}), pinned on {source.get('pinned_at', 'n/a')}.",
        "",
        f"- **Upstream project:** <{repo}>",
        f"- **Original author:** {source.get('author', 'see upstream')}",
        f"- **Upstream licence:** {source.get('license', 'see upstream')}, reproduced verbatim in [`LICENSE.upstream`](./LICENSE.upstream)",
        f"- **Tracked by:** [`skills/vendor.manifest.json`](../vendor.manifest.json)",
        f"- **Refreshed by:** [`scripts/sync_vendor.py`](../../scripts/sync_vendor.py), run every two weeks by [`.github/workflows/sync-vendored-skills.yml`](../../.github/workflows/sync-vendored-skills.yml)",
    ]
    if source.get("upstream_of_upstream"):
        out.append(
            f"- **Upstream's own source:** {source['upstream_of_upstream']} (pstack is a mirror kept in sync for standalone use)"
        )
    out += [
        "",
        "No functional changes were made to the vendored content. This repository adds only a",
        "`PROVENANCE.md` inside each skill directory and this file.",
        "",
        f"## Imported skills ({len(skills)})",
        "",
        "| Skill | Upstream permalink |",
        "| --- | --- |",
    ]
    sub = source.get("source_subpath", "").strip("/")
    for skill in skills:
        p = f"{sub}/{skill}" if sub else skill
        out.append(f"| [`{skill}`](./{skill}/) | [`{p}`]({repo}/tree/{sha}/{p}) |")

    mandatory = source.get("mandatory") or []
    if mandatory:
        out += [
            "",
            "## Mandatory imports",
            "",
            source.get("mandatory_reason", ""),
            "",
        ]
        for m in mandatory:
            out.append(f"- [`{m}`](./{m}/)")

    if excluded:
        out += [
            "",
            "## Deliberate exclusions",
            "",
            "Upstream skills left out of this repository, and why. Recorded so the decision is",
            "auditable rather than looking like an incomplete import.",
            "",
            "| Upstream skill | Reason |",
            "| --- | --- |",
        ]
        for name in sorted(excluded):
            out.append(f"| `{name}` | {excluded[name]} |")

    if source.get("notes"):
        out += ["", "## Notes", "", source["notes"]]
    out.append("")
    return "\n".join(out)


